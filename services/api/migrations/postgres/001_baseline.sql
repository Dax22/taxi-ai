CREATE TABLE driver_availability (
  id TEXT PRIMARY KEY,
  driver_id TEXT NOT NULL REFERENCES drivers(user_id) DEFERRABLE INITIALLY IMMEDIATE,
  active BIGINT NOT NULL CHECK (active IN (0, 1)),
  mode TEXT NOT NULL CHECK (mode IN ('gps', 'sample')),
