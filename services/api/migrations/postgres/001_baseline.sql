-- PostgreSQL 16+ baseline corresponding to SQLite schema 27.
-- JSON stays text at the repository boundary; indexed expressions cast to jsonb.
-- Epoch milliseconds and money require BIGINT; booleans retain the existing 0/1 contract.

CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email CITEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('customer', 'driver', 'admin')),
  created_at BIGINT NOT NULL
);

CREATE TABLE drivers (
  user_id TEXT PRIMARY KEY REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  vehicle_model TEXT NOT NULL,
  vehicle_plate TEXT NOT NULL,
  reviewed_by TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  reviewed_at BIGINT
);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  csrf_token TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);

CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE rides (
  id TEXT PRIMARY KEY,
  customer_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  driver_id TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  pickup_id TEXT NOT NULL,
  destination_id TEXT NOT NULL CHECK (destination_id <> pickup_id),
  suggested_fare_kobo BIGINT NOT NULL CHECK (suggested_fare_kobo > 0),
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'negotiating', 'agreed', 'cancelled')),
  version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
  created_at BIGINT NOT NULL,
  matched_at BIGINT,
  updated_at BIGINT NOT NULL, request_expires_at BIGINT, closed_reason TEXT CHECK (closed_reason IS NULL OR closed_reason = 'request_expired'), driver_snapshot_json TEXT, vehicle_category TEXT NOT NULL DEFAULT 'standard'
  CHECK (vehicle_category IN ('standard', 'suv', 'van', 'truck', 'motorcycle')),
  CHECK (driver_id IS NULL OR driver_id <> customer_id),
  CHECK (status NOT IN ('negotiating', 'agreed') OR (driver_id IS NOT NULL AND matched_at IS NOT NULL))
);

CREATE UNIQUE INDEX one_open_customer_request ON rides(customer_id) WHERE status IN ('requested', 'negotiating');

CREATE UNIQUE INDEX one_driver_negotiation ON rides(driver_id) WHERE status = 'negotiating';

CREATE INDEX rides_available ON rides(status, created_at);

CREATE INDEX rides_driver ON rides(driver_id, created_at);

CREATE TABLE fare_events (
  ride_id TEXT NOT NULL REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL CHECK (version > 0),
  type TEXT NOT NULL CHECK (type IN ('propose', 'accept', 'cancel')),
  payload TEXT NOT NULL,
  PRIMARY KEY (ride_id, version)
);

CREATE TABLE audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  kind TEXT NOT NULL,
  subject_id TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE rate_limits (
  key TEXT PRIMARY KEY,
  count BIGINT NOT NULL,
  reset_at BIGINT NOT NULL
);

CREATE TABLE chat_messages (
  id TEXT PRIMARY KEY,
  ride_id TEXT NOT NULL REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  sequence BIGINT NOT NULL CHECK (sequence > 0),
  sender_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
  created_at BIGINT NOT NULL,
  UNIQUE (ride_id, sequence)
);

CREATE TABLE chat_reads (
  ride_id TEXT NOT NULL REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  user_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  through_sequence BIGINT NOT NULL CHECK (through_sequence >= 0),
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (ride_id, user_id)
