CREATE TABLE chat_reports (
  id TEXT PRIMARY KEY,
  message_id TEXT NOT NULL REFERENCES chat_messages(id) DEFERRABLE INITIALLY IMMEDIATE,
  reporter_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  reason TEXT NOT NULL CHECK (reason IN ('harassment', 'unsafe_request', 'spam', 'other')),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'reviewed')),
  created_at BIGINT NOT NULL,
  reviewed_by TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  reviewed_at BIGINT,
  UNIQUE (message_id, reporter_id)
