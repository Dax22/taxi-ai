CREATE TABLE chat_commands (
  actor_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  key TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  message_id TEXT NOT NULL REFERENCES chat_messages(id) DEFERRABLE INITIALLY IMMEDIATE,
  PRIMARY KEY (actor_id, key)
