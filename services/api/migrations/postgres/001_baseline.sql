CREATE INDEX chat_reports_queue ON chat_reports(status, created_at);

CREATE TABLE ride_trips (
  ride_id TEXT PRIMARY KEY REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  customer_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  driver_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  status TEXT NOT NULL CHECK (status IN ('booked', 'on_way', 'arrived', 'in_progress', 'completed', 'cancelled')),
  fare_kobo BIGINT NOT NULL CHECK (fare_kobo > 0),
  booked_at BIGINT NOT NULL,
  departed_at BIGINT,
  arrived_at BIGINT,
  started_at BIGINT,
  completed_at BIGINT,
  pickup_pin TEXT,
  pin_failures BIGINT NOT NULL DEFAULT 0 CHECK (pin_failures BETWEEN 0 AND 5),
  pin_blocked_until BIGINT,
  CHECK (driver_id <> customer_id),
  CHECK ((status IN ('booked', 'on_way', 'arrived') AND pickup_pin IS NOT NULL AND length(pickup_pin) = 6 AND pickup_pin !~ '[^0-9]')
    OR (status IN ('in_progress', 'completed', 'cancelled') AND pickup_pin IS NULL)),
  CHECK (status NOT IN ('on_way', 'arrived', 'in_progress', 'completed') OR departed_at IS NOT NULL),
  CHECK (status NOT IN ('arrived', 'in_progress', 'completed') OR arrived_at IS NOT NULL),
  CHECK (status NOT IN ('in_progress', 'completed') OR started_at IS NOT NULL),
  CHECK (status <> 'completed' OR completed_at IS NOT NULL)
);

CREATE UNIQUE INDEX one_customer_trip ON ride_trips(customer_id) WHERE status NOT IN ('completed', 'cancelled');

CREATE UNIQUE INDEX one_driver_trip ON ride_trips(driver_id) WHERE status NOT IN ('completed', 'cancelled');

CREATE TABLE ride_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ride_id TEXT NOT NULL REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  actor_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  type TEXT NOT NULL CHECK (type IN ('booked', 'on_way', 'arrived', 'in_progress', 'completed', 'cancelled')),
  reason TEXT CHECK (reason IN ('plans_changed', 'pickup_problem', 'other')),
  created_at BIGINT NOT NULL,
  CHECK ((type = 'cancelled' AND reason IS NOT NULL) OR (type <> 'cancelled' AND reason IS NULL))
);

CREATE INDEX ride_activity_ride ON ride_activity(ride_id, id);

CREATE TABLE voice_calls (
  id TEXT PRIMARY KEY,
  ride_id TEXT NOT NULL REFERENCES rides(id) DEFERRABLE INITIALLY IMMEDIATE,
  caller_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  callee_id TEXT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  status TEXT NOT NULL CHECK (status IN ('ringing', 'connecting', 'connected', 'ended', 'declined', 'missed', 'failed')),
  mode TEXT NOT NULL CHECK (mode IN ('local', 'relay')),
  version BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  answered_at BIGINT,
  connected_at BIGINT,
  ended_at BIGINT,
  ended_by TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  reason TEXT,
  caller_session TEXT NOT NULL,
  callee_session TEXT,
  caller_client TEXT NOT NULL,
  callee_client TEXT,
  caller_seen_at BIGINT NOT NULL,
  callee_seen_at BIGINT,
  caller_connected BIGINT NOT NULL DEFAULT 0 CHECK (caller_connected IN (0, 1)),
  callee_connected BIGINT NOT NULL DEFAULT 0 CHECK (callee_connected IN (0, 1)),
  offer_sdp TEXT,
  answer_sdp TEXT,
  CHECK (caller_id <> callee_id),
  CHECK (status NOT IN ('connecting', 'connected') OR (answered_at IS NOT NULL AND callee_session IS NOT NULL AND callee_client IS NOT NULL)),
  CHECK (status <> 'connected' OR connected_at IS NOT NULL),
  CHECK (status IN ('ringing', 'connecting', 'connected') OR (ended_at IS NOT NULL AND offer_sdp IS NULL AND answer_sdp IS NULL))
);

CREATE INDEX voice_calls_caller ON voice_calls(caller_id, created_at);

CREATE INDEX voice_calls_callee ON voice_calls(callee_id, created_at);

CREATE INDEX voice_calls_ride ON voice_calls(ride_id, created_at);

CREATE UNIQUE INDEX one_voice_call_per_ride ON voice_calls(ride_id) WHERE status IN ('ringing', 'connecting', 'connected');

